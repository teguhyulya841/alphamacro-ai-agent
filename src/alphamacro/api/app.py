"""FastAPI application factory.

Note: do NOT add ``from __future__ import annotations`` here. FastAPI must resolve the
``Depends(...)`` annotations of endpoints that are defined inside ``create_app``.
"""

import asyncio
import inspect
import logging
import re
import uuid
from typing import Annotated, Any, Literal

from fastapi import (
    Depends,
    FastAPI,
    Header,
    HTTPException,
    Path,
    Query,
    Request,
    Response,
)
from pydantic import BaseModel, Field

from alphamacro import __version__
from alphamacro.api.auth import verify_key
from alphamacro.config import ApiSettings, StateSettings
from alphamacro.constants import DISCLAIMER
from alphamacro.exceptions import (
    AgentExecutionError,
    CoinNotFoundError,
    InvalidQueryError,
    MarketDataError,
    PolicyViolationError,
)
from alphamacro.infra.state import StateBundle, build_state
from alphamacro.models import (
    AgentResult,
    ConfidenceReport,
    GroundingReport,
    Observation,
    RateRule,
    Source,
    StateBackend,
)
from alphamacro.tools import AsyncCoinGeckoClient, async_fetch_snapshot, fetch_snapshot

logger = logging.getLogger("alphamacro.api")

_REQUEST_ID_RE = re.compile(r"^[A-Za-z0-9._-]{8,64}$")
_PLAIN_DISCLAIMER = DISCLAIMER.strip("*")


class AnalyzeRequest(BaseModel):
    query: str = Field(min_length=1, max_length=5000, description="Pertanyaan riset.")


class AnalyzeResponse(BaseModel):
    """API response schema derived directly from core domain models."""

    request_id: str
    category: str
    analysis_time: str
    report: str = Field(description="Markdown report body generated by the model.")
    tools_used: list[str]
    sources: list[Source]
    warnings: list[str]
    compliance_flags: list[str]
    grounding: GroundingReport | None
    observations: list[Observation] = Field(default_factory=list)
    confidence: ConfidenceReport | None = None
    latency_seconds: float
    model: str
    disclaimer: str

    @classmethod
    def from_result(cls, result: Any) -> "AnalyzeResponse":
        grounding = None
        if getattr(result, "grounding", None) is not None:
            g = result.grounding
            grounding = GroundingReport(
                total=g.total,
                verified=g.verified,
                score=g.score,
                ungrounded=list(g.ungrounded),
            )
        confidence = None
        if getattr(result, "confidence", None) is not None:
            c = result.confidence
            confidence = ConfidenceReport(
                level=c.level,
                score=c.score,
                grounding_score=c.grounding_score,
                observation_count=c.observation_count,
                stale_observations=c.stale_observations,
                max_age_s=c.max_age_s,
                reasons=list(c.reasons),
            )
        observations = [
            Observation(
                source=o.source,
                endpoint=o.endpoint,
                entity=o.entity,
                observed_at=o.observed_at,
                fetched_at=o.fetched_at,
                freshness=o.freshness,
                age_s=o.age_s,
                metrics=dict(o.metrics),
                urls=list(o.urls),
            )
            for o in getattr(result, "observations", [])
        ]
        return cls(
            request_id=result.request_id,
            category=result.category,
            analysis_time=result.analysis_time,
            report=result.report,
            tools_used=list(result.tools_used),
            sources=[Source(title=s.title, url=s.url) for s in result.sources],
            warnings=list(result.warnings),
            compliance_flags=list(result.compliance_flags),
            grounding=grounding,
            observations=observations,
            confidence=confidence,
            latency_seconds=result.latency_seconds,
            model=result.model,
            disclaimer=_PLAIN_DISCLAIMER,
        )


class ErrorBody(BaseModel):
    code: str
    message: str
    request_id: str | None = None


def _error(
    status: int,
    code: str,
    message: str,
    request_id: str | None,
    headers: dict[str, str] | None = None,
) -> HTTPException:
    detail = ErrorBody(code=code, message=message, request_id=request_id).model_dump()
    return HTTPException(status_code=status, detail=detail, headers=headers)


def _to_response(result: AgentResult) -> AnalyzeResponse:
    return AnalyzeResponse.from_result(result)


def create_app(
    engine: Any,
    settings: ApiSettings,
    *,
    market_client: Any | None = None,
    state_bundle: StateBundle | None = None,
) -> FastAPI:
    """Build the async FastAPI application with injected engine and state ports."""
    app = FastAPI(
        title="AlphaMacro-Crypto API",
        version=__version__,
        description=(
            "AI macro & crypto research with verifiable output. Informational only; "
            "not investment advice."
        ),
    )
    bundle = (
        state_bundle
        if state_bundle is not None
        else getattr(engine, "state", None)
        or build_state(StateSettings(backend=StateBackend.MEMORY))
    )
    rate_rule = RateRule(limit=settings.rate_limit_per_minute, window_s=60)
    semaphore = asyncio.Semaphore(settings.max_concurrent_requests)
    client = (
        market_client
        if market_client is not None
        else getattr(engine, "market_client", None)
    )

    @app.middleware("http")
    async def request_id_middleware(request: Request, call_next):  # noqa: ANN001, ANN202
        supplied = request.headers.get("x-request-id", "")
        request.state.request_id = (
            supplied if _REQUEST_ID_RE.match(supplied) else uuid.uuid4().hex[:16]
        )
        response = await call_next(request)
        response.headers["X-Request-ID"] = request.state.request_id
        response.headers["Cache-Control"] = "no-store"
        return response

    async def authenticate(
        request: Request,
        x_api_key: Annotated[str | None, Header(alias="X-API-Key")] = None,
    ) -> str:
        name = verify_key(x_api_key, settings.api_key_hashes)
        if name is None:
            raise _error(
                401,
                "unauthorized",
                "API key tidak valid atau tidak ada.",
                request.state.request_id,
            )
        decision = await bundle.limiter.check(name, rate_rule)
        if not decision.allowed:
            wait = int(decision.retry_after_s) + 1
            raise _error(
                429,
                "rate_limited",
                f"Terlalu banyak permintaan. Coba lagi dalam {wait} detik.",
                request.state.request_id,
                {"Retry-After": str(wait)},
            )
        return name

    Caller = Annotated[str, Depends(authenticate)]

    @app.get("/healthz", tags=["ops"])
    async def healthz() -> dict[str, str]:
        return {"status": "ok"}

    @app.get("/readyz", tags=["ops"])
    async def readyz() -> dict[str, str]:
        return {"status": "ready", "version": __version__}

    @app.post(
        "/v1/analyze",
        response_model=AnalyzeResponse,
        tags=["research"],
        responses={
            400: {"model": ErrorBody},
            401: {"model": ErrorBody},
            429: {"model": ErrorBody},
        },
    )
    async def analyze(
        body: AnalyzeRequest, request: Request, caller: Caller
    ) -> AnalyzeResponse:
        request_id = request.state.request_id
        if semaphore.locked():
            raise _error(
                503,
                "busy",
                "Server sedang sibuk. Coba lagi sebentar lagi.",
                request_id,
                {"Retry-After": "5"},
            )
        async with semaphore:
            try:
                arun = getattr(engine, "arun", None)
                if inspect.iscoroutinefunction(arun):
                    result = await arun(
                        body.query,
                        user_id=caller,
                        channel="api",
                        request_id=request_id,
                    )
                else:
                    result = await asyncio.to_thread(
                        engine.run,
                        body.query,
                        user_id=caller,
                        channel="api",
                        request_id=request_id,
                    )
            except PolicyViolationError as exc:
                raise _error(400, "policy_violation", str(exc), request_id) from exc
            except InvalidQueryError as exc:
                raise _error(400, "invalid_query", str(exc), request_id) from exc
            except AgentExecutionError as exc:
                logger.error("Analysis failed request_id=%s", request_id)
                raise _error(
                    502,
                    "analysis_failed",
                    "Analisis gagal. Silakan coba lagi nanti.",
                    request_id,
                ) from exc
        return _to_response(result)

    @app.get("/v1/indicators/{coin_id}", tags=["research"])
    async def indicators(
        request: Request,
        caller: Caller,
        coin_id: Annotated[str, Path(pattern=r"^[a-z0-9][a-z0-9\-]{0,63}$")],
        timeframe: Annotated[Literal["daily", "4h"], Query()] = "daily",
    ) -> dict[str, Any]:
        """Deterministic technical indicators computed from market data (no LLM)."""
        request_id = request.state.request_id
        if client is None:
            raise _error(503, "unavailable", "Data pasar tidak tersedia.", request_id)
        try:
            if isinstance(client, AsyncCoinGeckoClient) or inspect.iscoroutinefunction(
                getattr(client, "get_daily_closes", None)
            ):
                snapshot = await async_fetch_snapshot(client, coin_id, timeframe)
            else:
                snapshot = await asyncio.to_thread(
                    fetch_snapshot, client, coin_id, timeframe
                )
        except CoinNotFoundError as exc:
            raise _error(
                404, "coin_not_found", "Coin ID tidak ditemukan.", request_id
            ) from exc
        except MarketDataError as exc:
            raise _error(502, "market_data_error", str(exc), request_id) from exc
        return {
            "request_id": request_id,
            "indicators": snapshot,
            "disclaimer": _PLAIN_DISCLAIMER,
        }

    @app.exception_handler(Exception)
    async def unhandled(request: Request, exc: Exception) -> Response:  # noqa: ARG001
        from fastapi.responses import JSONResponse

        request_id = getattr(request.state, "request_id", None)
        logger.exception("Unhandled error request_id=%s", request_id)
        body = ErrorBody(
            code="internal_error",
            message="Terjadi kesalahan internal.",
            request_id=request_id,
        )
        return JSONResponse(status_code=500, content={"detail": body.model_dump()})

    return app
